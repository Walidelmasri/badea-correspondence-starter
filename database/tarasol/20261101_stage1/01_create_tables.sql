-- Run 00_preflight.sql before this script, as STRATEGYKPI (F5 / script mode).
-- Oracle DDL auto-commits: review all statements before executing.
-- This migration deliberately does not create/write to BADEA_ADDONS objects.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON
DECLARE
    v_existing NUMBER;
BEGIN
    IF USER <> 'STRATEGYKPI'
       OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'STRATEGYKPI' THEN
        RAISE_APPLICATION_ERROR(-20001, 'STOP: wrong Oracle schema');
    END IF;
    SELECT COUNT(*) INTO v_existing FROM USER_OBJECTS
    WHERE OBJECT_NAME IN (
      'TARASOL_ORG_UNITS', 'TARASOL_UNIT_ASSIGNMENTS',
      'TARASOL_SECRETARY_ASSIGNMENTS', 'TARASOL_DELEGATIONS'
    );
    IF v_existing <> 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'STOP: Stage 1 objects already exist');
    END IF;
END;
/

CREATE TABLE TARASOL_ORG_UNITS (
    UNIT_CODE       VARCHAR2(3 CHAR) NOT NULL,
    NAME_EN         VARCHAR2(255 CHAR) NOT NULL,
    NAME_AR         NVARCHAR2(255),
    NAME_FR         VARCHAR2(255 CHAR),
    UNIT_TYPE       VARCHAR2(16 CHAR) DEFAULT 'OTHER' NOT NULL,
    STATUS          CHAR(1) DEFAULT 'A' NOT NULL,
    SAP_CODE        NUMBER(10),
    CREATED_AT      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT TARASOL_ORG_PK PRIMARY KEY (UNIT_CODE),
    CONSTRAINT TARASOL_ORG_CODE_CK CHECK (REGEXP_LIKE(UNIT_CODE, '^[0-9]{3}$')),
    CONSTRAINT TARASOL_ORG_TYPE_CK CHECK (UNIT_TYPE IN ('DEPARTMENT','OFFICE','OTHER')),
    CONSTRAINT TARASOL_ORG_STATUS_CK CHECK (STATUS IN ('A','I'))
);

CREATE TABLE TARASOL_UNIT_ASSIGNMENTS (
    ASSIGNMENT_ID       NUMBER GENERATED ALWAYS AS IDENTITY,
    UNIT_CODE           VARCHAR2(3 CHAR) NOT NULL,
    EMP_ID              VARCHAR2(20 CHAR) NOT NULL,
    CAPACITY            VARCHAR2(24 CHAR) NOT NULL,
    STARTS_AT           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ENDS_AT             TIMESTAMP(6) WITH TIME ZONE,
    APPOINTMENT_REF     VARCHAR2(120 CHAR),
    APPROVED_BY_EMP_ID  VARCHAR2(20 CHAR) NOT NULL,
    CREATED_BY_EMP_ID   VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REVOKED_AT          TIMESTAMP(6) WITH TIME ZONE,
    REVOKED_BY_EMP_ID   VARCHAR2(20 CHAR),
    REVOKE_REASON       VARCHAR2(500 CHAR),
    CONSTRAINT TARASOL_UA_PK PRIMARY KEY (ASSIGNMENT_ID),
    CONSTRAINT TARASOL_UA_UNIT_FK FOREIGN KEY (UNIT_CODE)
        REFERENCES TARASOL_ORG_UNITS(UNIT_CODE),
    CONSTRAINT TARASOL_UA_ID_UNIT_UK UNIQUE (ASSIGNMENT_ID, UNIT_CODE),
    CONSTRAINT TARASOL_UA_CAP_CK CHECK (
        CAPACITY IN ('MANAGER','ACTING_MANAGER','OFFICE_MEMBER','CONSULTANT')
    ),
    CONSTRAINT TARASOL_UA_DATES_CK CHECK (ENDS_AT IS NULL OR ENDS_AT > STARTS_AT),
    CONSTRAINT TARASOL_UA_REVOKE_CK CHECK (
        (REVOKED_AT IS NULL AND REVOKED_BY_EMP_ID IS NULL)
        OR (REVOKED_AT IS NOT NULL AND REVOKED_BY_EMP_ID IS NOT NULL)
    )
);

CREATE INDEX TARASOL_UA_EMP_IDX
    ON TARASOL_UNIT_ASSIGNMENTS (EMP_ID, UNIT_CODE, CAPACITY, STARTS_AT);
CREATE INDEX TARASOL_UA_UNIT_IDX
    ON TARASOL_UNIT_ASSIGNMENTS (UNIT_CODE, CAPACITY, REVOKED_AT, STARTS_AT);

CREATE TABLE TARASOL_SECRETARY_ASSIGNMENTS (
    SECRETARY_ASSIGNMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    UNIT_CODE               VARCHAR2(3 CHAR) NOT NULL,
    MANAGER_ASSIGNMENT_ID   NUMBER NOT NULL,
    SECRETARY_EMP_ID        VARCHAR2(20 CHAR) NOT NULL,
    STARTS_AT               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ENDS_AT                 TIMESTAMP(6) WITH TIME ZONE,
    APPROVED_BY_EMP_ID      VARCHAR2(20 CHAR) NOT NULL,
    CREATED_BY_EMP_ID       VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REVOKED_AT              TIMESTAMP(6) WITH TIME ZONE,
    REVOKED_BY_EMP_ID       VARCHAR2(20 CHAR),
    REVOKE_REASON           VARCHAR2(500 CHAR),
    CONSTRAINT TARASOL_SA_PK PRIMARY KEY (SECRETARY_ASSIGNMENT_ID),
    CONSTRAINT TARASOL_SA_UNIT_FK FOREIGN KEY (UNIT_CODE)
        REFERENCES TARASOL_ORG_UNITS(UNIT_CODE),
    CONSTRAINT TARASOL_SA_MANAGER_FK
        FOREIGN KEY (MANAGER_ASSIGNMENT_ID, UNIT_CODE)
        REFERENCES TARASOL_UNIT_ASSIGNMENTS(ASSIGNMENT_ID, UNIT_CODE),
    CONSTRAINT TARASOL_SA_DATES_CK CHECK (ENDS_AT IS NULL OR ENDS_AT > STARTS_AT),
    CONSTRAINT TARASOL_SA_REVOKE_CK CHECK (
        (REVOKED_AT IS NULL AND REVOKED_BY_EMP_ID IS NULL)
        OR (REVOKED_AT IS NOT NULL AND REVOKED_BY_EMP_ID IS NOT NULL)
    )
);

CREATE INDEX TARASOL_SA_SECRETARY_IDX
    ON TARASOL_SECRETARY_ASSIGNMENTS (SECRETARY_EMP_ID, UNIT_CODE, STARTS_AT);
CREATE INDEX TARASOL_SA_MANAGER_IDX
    ON TARASOL_SECRETARY_ASSIGNMENTS (MANAGER_ASSIGNMENT_ID, REVOKED_AT);

CREATE TABLE TARASOL_DELEGATIONS (
    DELEGATION_ID           NUMBER GENERATED ALWAYS AS IDENTITY,
    UNIT_CODE               VARCHAR2(3 CHAR) NOT NULL,
    MANAGER_ASSIGNMENT_ID   NUMBER NOT NULL,
    DELEGATE_EMP_ID         VARCHAR2(20 CHAR) NOT NULL,
    DELEGATION_TYPE         VARCHAR2(20 CHAR) NOT NULL,
    CASE_TECHNICAL_ID       VARCHAR2(80 CHAR),
    STARTS_AT               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ENDS_AT                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    APPROVED_BY_EMP_ID      VARCHAR2(20 CHAR) NOT NULL,
    CREATED_BY_EMP_ID       VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REVOKED_AT              TIMESTAMP(6) WITH TIME ZONE,
    REVOKED_BY_EMP_ID       VARCHAR2(20 CHAR),
    REVOKE_REASON           VARCHAR2(500 CHAR),
    CONSTRAINT TARASOL_DELEG_PK PRIMARY KEY (DELEGATION_ID),
    CONSTRAINT TARASOL_DELEG_UNIT_FK FOREIGN KEY (UNIT_CODE)
        REFERENCES TARASOL_ORG_UNITS(UNIT_CODE),
    CONSTRAINT TARASOL_DELEG_MGR_FK
        FOREIGN KEY (MANAGER_ASSIGNMENT_ID, UNIT_CODE)
        REFERENCES TARASOL_UNIT_ASSIGNMENTS(ASSIGNMENT_ID, UNIT_CODE),
    CONSTRAINT TARASOL_DELEG_TYPE_CK CHECK (
        DELEGATION_TYPE IN ('LEAVE_COVER','CASE_HANDOFF')
    ),
    CONSTRAINT TARASOL_DELEG_CASE_CK CHECK (
        (DELEGATION_TYPE = 'CASE_HANDOFF' AND CASE_TECHNICAL_ID IS NOT NULL)
        OR (DELEGATION_TYPE = 'LEAVE_COVER' AND CASE_TECHNICAL_ID IS NULL)
    ),
    CONSTRAINT TARASOL_DELEG_DATES_CK CHECK (ENDS_AT > STARTS_AT),
    CONSTRAINT TARASOL_DELEG_REVOKE_CK CHECK (
        (REVOKED_AT IS NULL AND REVOKED_BY_EMP_ID IS NULL)
        OR (REVOKED_AT IS NOT NULL AND REVOKED_BY_EMP_ID IS NOT NULL)
    )
);

CREATE INDEX TARASOL_DELEG_EMP_IDX
    ON TARASOL_DELEGATIONS (DELEGATE_EMP_ID, UNIT_CODE, STARTS_AT);
CREATE INDEX TARASOL_DELEG_MGR_IDX
    ON TARASOL_DELEGATIONS (MANAGER_ASSIGNMENT_ID, REVOKED_AT);

COMMENT ON TABLE TARASOL_UNIT_ASSIGNMENTS IS
   'Tarasol unit capacities; active manager vacancy and interval rules enforced by future management service.';
COMMENT ON TABLE TARASOL_SECRETARY_ASSIGNMENTS IS
   'Secretary-to-specific-manager relationship; future service validates manager role and dates.';
COMMENT ON TABLE TARASOL_DELEGATIONS IS
   'Temporary authorization requests; no existing Tarasol API reads this table in Stage 1.';
